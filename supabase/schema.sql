-- Skema Referensi WawanFarm Smart Agri-CRM (sesuai tabel live Supabase)
-- Jalankan di Supabase SQL Editor bila perlu mengaktifkan RLS & Super Admin.

-- 1. Tabel packages
create table if not exists public.packages (
  id bigint generated by default as identity primary key,
  package_name text not null,
  period text not null,
  price integer not null,
  features text not null
);

-- 2. Tabel crops_iot
create table if not exists public.crops_iot (
  id bigint generated by default as identity primary key,
  crop_name text not null,
  bed_location text not null,
  soil_moisture numeric not null,
  temperature numeric not null,
  organic_fertilizer text not null,
  last_fertilized text not null,
  harvest_days_left integer not null,
  status text not null,
  updated_at timestamptz not null default now()
);

-- 3. Tabel profiles
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  phone text,
  address text,
  active_package text,
  updated_at timestamptz default now()
);

-- 4. Tabel orders
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  package_name text not null,
  total_price integer not null,
  order_status text not null default 'Menunggu Pembayaran',
  created_at timestamptz not null default now()
);

